"""World definition for the Roman total conversion ("Orbis Romanus").

The coastlines below are written in real longitude/latitude and projected into
Warband's map space:

    x = (lon - 20) * 8.8      -> lon 20E is the middle of the map, x in [-281, 281]
    y = (lat - 38.5) * 10.6   -> lat 38.5N is the middle, y in [-212, 213]

The projection keeps the shape of the Mediterranean recognisable: the Italian
peninsula, Greece with its islands, Iberia, Gaul, Britain, the Anatolian and
Levantine coasts, the Nile valley and the North African shore.
"""

X0, Y0 = 20.0, 38.5
SX, SY = 12.7, 15.0

# the world is built for the full Warband map grid (+-400), not a small centre box
BX, BY = 380.0, 380.0
K = SX / 5.4   # distance scale factor used by the builder


def P(lon, lat):
    """Project a geographic point into map space."""
    return ((lon - X0) * SX, (lat - Y0) * SY)


def _poly(*pts):
    return [P(lon, lat) for lon, lat in pts]


